#!/usr/bin/env python3
"""Create golden vectors for checking the Android ByteLevel BPE implementation."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from tokenizers import Tokenizer


SAMPLES = [
    "Привет! Как дела?",
    "Русский текст: ёжик, подъезд, съёмка, объём.",
    "Тоҷикӣ: салом, дӯсти ман. Чӣ хабар?",
    "English: don't stop; we're testing 12345.",
    "🙂 🚀 — café / cafe\u0301 / naïve.",
    'def greet(name: str) -> str:\n    return f"Привет, {name}!"\n',
    "Скобки [] {} () <> != == // # и пунктуация...",
    "Пробелы  между\tсловами\nи новая строка.",
    "مرحبا بالعالم — multilingual UTF-8 test.",
    "UPPERCASE 'S 'RE 'LL must follow the exact GPT-2 split rules.",
]


def build_fixture(tokenizer_path: str | Path) -> dict:
    tokenizer = Tokenizer.from_file(str(tokenizer_path))
    model = tokenizer.to_str()
    parsed = json.loads(model)
    if parsed.get("model", {}).get("type") != "BPE":
        raise ValueError("Expected a BPE tokenizer")
    cases = []
    for text in SAMPLES:
        ids = tokenizer.encode(text).ids
        decoded = tokenizer.decode(ids, skip_special_tokens=True)
        cases.append({"text": text, "ids": ids, "decoded": decoded})
    return {
        "format": 1,
        "description": "Golden token IDs generated by the canonical Hugging Face tokenizer.json",
        "vocab_size": tokenizer.get_vocab_size(),
        "cases": cases,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tokenizer", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    fixture = build_fixture(args.tokenizer)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(fixture, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Tokenizer parity fixture: {len(fixture['cases'])} cases, vocab={fixture['vocab_size']}")
    for case in fixture["cases"]:
        print(f"  {len(case['ids']):4d} tokens | {case['text'][:72]!r}")


if __name__ == "__main__":
    main()
