    fun respond(text: String, teacherMode: Boolean = false): String? {
        val q = text.lowercase()
        val explicit = listOf("урок", "объясни", "научи", "lesson").any { q.contains(it) }
        val quiz = listOf("тест", "практика", "quiz").any { q.contains(it) }
        if (!teacherMode && !explicit && !quiz) return null
        val index = when {
            listOf("python", "питон", "переменн").any { q.contains(it) } -> 0
            listOf("услов", "if").any { q.contains(it) } -> 1
            listOf("цикл", "for", "while").any { q.contains(it) } -> 2
            listOf("функц", "def", "return").any { q.contains(it) } -> 3
            listOf("c++", "с++", "cpp").any { q.contains(it) } -> 4
            listOf("алгеб", "уравнен").any { q.contains(it) } -> 5
            listOf("дроб").any { q.contains(it) } -> 6
            listOf("физик", "скорост").any { q.contains(it) } -> 7
            listOf("хими", "атом").any { q.contains(it) } -> 8
            listOf("биолог", "клет").any { q.contains(it) } -> 9
            listOf("godot", "гдот").any { q.contains(it) } -> 10
            listOf("нейросет", "нейрон", "вес").any { q.contains(it) } -> 11
            else -> -1
        }
        if (index < 0) return "NYXVAULT ACADEMY • ПЛАН ОБУЧЕНИЯ\n\nДоступные уроки:\n" +
            lessons.joinToString("\n") { "• " + it.title } +
            "\n\nНапиши, например: «Объясни Python: циклы» или «Урок по физике: скорость»."
        val lesson = lessons[index]
        return if (quiz) {
            "NYXVAULT ACADEMY • ПРАКТИКА\n" + lesson.title + "\n\n" + lesson.practice +
                "\n\nСначала реши самостоятельно. Затем напиши свой ответ — я покажу разбор темы."
        } else {
            "NYXVAULT ACADEMY • УРОК\n" + lesson.title + "\n\nОБЪЯСНЕНИЕ\n" +
                lesson.explanation + "\n\nПРИМЕР\n" + lesson.example + "\n\nПРАКТИКА\n" + lesson.practice
        }
    }
